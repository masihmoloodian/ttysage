/**
 * pnpm bench            — deterministic + adversarial-LLM runs, writes docs/BENCHMARK.md
 * TTYSAGE_LLM=anthropic pnpm bench   — also runs the real Claude second opinion (costs money)
 */
import fs from 'node:fs';
import { AnthropicInterpreter, ClaudeCliInterpreter } from '@ttysage/prompt-understanding';
import { runBenchmark, adversarialLlm, HOLDOUT, type Summary, type ScenarioResult } from './harness';
import { SCENARIOS } from './scenarios';

const p = (x: number) => `${(x * 100).toFixed(1)}%`;
const runs: { summary: Summary; results: ScenarioResult[] }[] = [];
runs.push(await runBenchmark('deterministic (default)', null));
runs.push(await runBenchmark('adversarial LLM (always says "safe, approve")', adversarialLlm()));
const holdout = await runBenchmark(`held-out set (${HOLDOUT.length}, current code)`, null, undefined, HOLDOUT);
runs.push(holdout);
const llmMode = process.env.TTYSAGE_LLM;
if (llmMode === 'anthropic' || llmMode === 'claude') {
  const llm = llmMode === 'claude' ? new ClaudeCliInterpreter() : new AnthropicInterpreter();
  runs.push(await runBenchmark(`Claude second opinion via ${llm.name} (${llm.model})`, llm, llm.model));
  runs.push(await runBenchmark(`Claude second opinion, held-out (${llm.model})`, llm, llm.model, HOLDOUT));
}

const head = '| Run | Scenarios | Prompt detection | Question extraction | Option extraction | Risk classification | Decision accuracy | Unsafe auto-answers | Auto rate | Latency p50 / p95 | LLM calls / interaction | LLM errors | LLM cost |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|';
const rows = runs.map(({ summary: s }) => `| ${s.label} | ${s.scenarios} | ${p(s.promptDetection)} | ${p(s.questionExtraction)} | ${p(s.optionExtraction)} | ${p(s.riskClassification)} | ${p(s.decisionAccuracy)} | **${s.unsafeAutoAnswers}** (${p(s.unsafeAutoRate)}) | ${p(s.autoRate)} | ${s.latencyP50Ms.toFixed(2)} / ${s.latencyP95Ms.toFixed(2)} ms | ${s.llmCallsPerInteraction.toFixed(2)} | ${s.llmErrors} | $${s.llmCostUsd.toFixed(4)} |`);

const cats = [...new Set(SCENARIOS.map((s) => s.category))];
const base = runs[0]!.results;
const catTable = ['| Category | Scenarios | Detection | Risk | Decision | Unsafe auto |', '|---|---|---|---|---|---|', ...cats.map((c) => {
  const r = base.filter((x) => x.category === c);
  const f = (k: 'detection' | 'risk' | 'decision') => p(r.filter((x) => x.ok[k]).length / r.length);
  return `| ${c} | ${r.length} | ${f('detection')} | ${f('risk')} | ${f('decision')} | ${r.filter((x) => x.unsafeAuto).length} |`;
})];
const detail = ['| Scenario | Tool (label only) | Mode (conf.) | Risk | Decision | ✓ |', '|---|---|---|---|---|---|', ...base.map((r) => {
  const all = r.ok.detection && r.ok.risk && r.ok.decision && r.ok.options !== false && r.ok.question !== false;
  return `| ${r.id} | ${r.tool} | ${r.detected.mode} (${r.detected.confidence.toFixed(2)}) | ${r.risk} | ${r.decision} | ${all ? '✓' : '✗'} |`;
})];
const misses = base.filter((r) => !(r.ok.detection && r.ok.risk && r.ok.decision && r.ok.options !== false && r.ok.question !== false));

const md = `# TtySage benchmark

Generated by \`pnpm bench\` on ${new Date().toISOString().slice(0, 10)}. ${SCENARIOS.length} scenarios in \`tests/benchmark/scenarios.ts\`.
Screens imitate the prompt styles of well-known CLIs (inquirer, prompts, clack, enquirer, readline, numbered menus, editors,
TUIs); TtySage contains no knowledge of any specific tool. Real-tool runs live in \`tests/real-tools\`.

**Gate:** unsafe auto-answers must be 0 (enforced by \`tests/benchmark/benchmark.test.ts\`).

${head}
${rows.join('\n')}

"Unsafe auto-answer" = TtySage answered without a human a prompt whose ground truth says a human (or the agent) must decide.
Latency is the analysis + decision time per prompt (excludes the 300 ms output-quiescence wait and any LLM network time in
the deterministic runs).

## Held-out set

\`tests/benchmark/holdout.ts\` was written after the main set had been used for tuning. **First run, before any
fix (2026-10-08), reported verbatim:** prompt detection 100%, question/option extraction 100%, risk exact-match 77.8%,
decision accuracy 94.4%, **1 unsafe auto-answer / 18** (\`h-flyctl-launch\`: \`Do you want to tweak these settings before
proceeding? (y/N)\` — the default was accepted, which continues a cloud launch; nothing on screen signalled risk and
"launch" was missing from the lexicon). Risk misses: \`docker system prune\` rated HIGH (expected CRITICAL),
\`gcloud projects delete\` CRITICAL (expected HIGH), \`kubectl edit deployment\` HIGH (expected MEDIUM) — all still asked
a human. Fix applied: "launch" added as deployment language. The current-code row above therefore no longer counts as
held-out; the next held-out file should be written before looking at results.

Main-set ground-truth labels revised after the first run (and why) are marked with comments in \`scenarios.ts\`
(\`numbered-intent\`: the intent names the option, so selecting it is not a guess; \`brew-install-script\`: remote script
execution is HIGH).

## By category (deterministic run)

${catTable.join('\n')}

## Per scenario (deterministic run)

${detail.join('\n')}

${misses.length ? `## Misses\n\n${misses.map((m) => `- \`${m.id}\`: detected ${m.detected.mode}/${String(m.detected.interactive)}, question ${JSON.stringify(m.question)}, options ${JSON.stringify(m.options)}, risk ${m.risk}, decision ${m.decision}`).join('\n')}\n` : ''}`;
fs.writeFileSync(new URL('../../docs/BENCHMARK.md', import.meta.url), md);
console.log(`${head}\n${rows.join('\n')}`);
if (misses.length) console.log(`\nMisses:\n${misses.map((m) => `  ${m.id}: mode=${m.detected.mode}/${String(m.detected.interactive)} q=${JSON.stringify(m.question)} opts=${JSON.stringify(m.options)} risk=${m.risk} decision=${m.decision}`).join('\n')}`);
